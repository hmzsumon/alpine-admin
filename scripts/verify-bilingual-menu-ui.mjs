/* ────────── read-only bilingual menu verification; no real order is submitted ────────── */
import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const origin = process.env.ALPINE_TEST_ORIGIN || "http://localhost:3100";
const apiOrigin = process.env.ALPINE_TEST_API || "http://127.0.0.1:4100";
const output = process.env.ALPINE_SCREENSHOT_DIR || path.resolve(import.meta.dirname, "../../screenshots");
await fs.mkdir(output, { recursive: true });
const credentials = JSON.parse(await fs.readFile(path.resolve(import.meta.dirname, "../../alpine-api/.initial-admin.json"), "utf8"));
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
let signedIn = false;
try {
  const login = await context.request.post(origin + "/api/auth/login", { headers: { Origin: origin }, data: credentials });
  assert.equal(login.status(), 200); signedIn = true;
  const response = await context.request.get(origin + "/api/state");
  assert.equal(response.status(), 200);
  const workspace = await response.json();
  assert(workspace.data.menu.every((item) => item.name && item.nameBn), "Every live menu item has both names");
  const token = (await context.cookies()).find((cookie) => cookie.name === "alpine_session")?.value;
  assert(token);
  const bootstrapResponse = await context.request.get(apiOrigin + "/api/waiter/bootstrap", { headers: { Authorization: "Bearer " + token } });
  assert.equal(bootstrapResponse.status(), 200);
  const bootstrap = await bootstrapResponse.json();
  assert(bootstrap.menu.length > 0 && bootstrap.menu.every((item) => item.nameBn), "Waiter bootstrap includes Bengali names");
  const page = await context.newPage();
  await page.goto(origin + "/menu", { waitUntil: "networkidle" });
  const search = page.getByPlaceholder("Search anything…");
  await search.fill("মুগ ডাল");
  await page.getByRole("button", { name: "Edit", exact: true }).first().waitFor();
  assert.equal(await page.locator("tbody tr").count(), 1);
  assert((await page.locator("tbody tr").innerText()).includes("Mug Dal"));
  await page.screenshot({ path: path.join(output, "alpine-bilingual-menu-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: "Edit", exact: true }).first().click();
  const dialog = page.getByRole("dialog");
  assert.equal(await dialog.getByLabel("Item name (English)").inputValue(), "Mug Dal");
  const bengali = dialog.getByLabel("আইটেমের বাংলা নাম");
  assert.equal(await bengali.inputValue(), "মুগ ডাল");
  await bengali.fill("");
  assert.equal(await bengali.evaluate((input) => input.validity.valueMissing), true);
  await bengali.fill("মুগ ডাল");
  await page.screenshot({ path: path.join(output, "alpine-bilingual-name-form.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.getByRole("button", { name: "New order", exact: true }).click();
  await dialog.getByPlaceholder("Search anything…").fill("মুগ ডাল");
  assert.equal(await dialog.locator(".menu-item-names strong").innerText(), "মুগ ডাল");
  assert.equal(await dialog.locator(".menu-item-names small").innerText(), "Mug Dal");
  await page.screenshot({ path: path.join(output, "alpine-bengali-first-order-picker.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForFunction(() => document.querySelector(".sidebar").getBoundingClientRect().right <= 1);
  await page.screenshot({ path: path.join(output, "alpine-bilingual-menu-mobile.png"), fullPage: true, animations: "disabled" });
  const sizes = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: window.innerWidth }));
  assert(sizes.content <= sizes.viewport + 1);
  console.log(`Bilingual UI passed: ${workspace.data.menu.length} live menu names, ${bootstrap.menu.length} waiter menu names, Bengali search, required name fields, Bengali-first order picker and mobile layout. No order or menu write submitted.`);
} finally {
  if (signedIn) await context.request.post(origin + "/api/auth/logout", { headers: { Origin: origin } }).catch(() => {});
  await context.close(); await browser.close();
}
